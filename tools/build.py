#!/usr/bin/env python3
"""Train a linear MNIST classifier and export its forward pass as CSS."""

from __future__ import annotations

import argparse
import urllib.request
from pathlib import Path

import numpy as np


ROOT = Path(__file__).resolve().parents[1]
DATASET = ROOT / "data" / "mnist.npz"
DATASET_URL = "https://storage.googleapis.com/tensorflow/tf-keras-datasets/mnist.npz"


def download_dataset() -> None:
    if DATASET.exists():
        return
    DATASET.parent.mkdir(parents=True, exist_ok=True)
    print(f"Downloading MNIST to {DATASET.relative_to(ROOT)}...")
    urllib.request.urlretrieve(DATASET_URL, DATASET)


def load_data() -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    download_dataset()
    with np.load(DATASET) as data:
        x_train = data["x_train"].reshape(-1, 784).astype(np.float32) / 255.0
        y_train = data["y_train"].astype(np.int64)
        x_test = data["x_test"].reshape(-1, 784).astype(np.float32) / 255.0
        y_test = data["y_test"].astype(np.int64)
    return x_train, y_train, x_test, y_test


def train(
    x_train: np.ndarray,
    y_train: np.ndarray,
    epochs: int,
    seed: int,
) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    """Train a 784 -> 32 -> 10 ReLU MLP with mini-batch Adam."""
    rng = np.random.default_rng(seed)
    hidden_size = 32
    weights_1 = (
        rng.normal(0, np.sqrt(2 / 784), size=(hidden_size, 784))
    ).astype(np.float32)
    bias_1 = np.zeros(hidden_size, dtype=np.float32)
    weights_2 = (
        rng.normal(0, np.sqrt(2 / hidden_size), size=(10, hidden_size))
    ).astype(np.float32)
    bias_2 = np.zeros(10, dtype=np.float32)
    batch_size = 256
    parameters = [weights_1, bias_1, weights_2, bias_2]
    first_moments = [np.zeros_like(parameter) for parameter in parameters]
    second_moments = [np.zeros_like(parameter) for parameter in parameters]
    step = 0

    for epoch in range(epochs):
        order = rng.permutation(len(x_train))
        learning_rate = 0.0025 / (1.0 + epoch * 0.08)
        for start in range(0, len(order), batch_size):
            step += 1
            indices = order[start : start + batch_size]
            batch_x = x_train[indices]
            batch_y = y_train[indices]

            hidden_pre = batch_x @ weights_1.T + bias_1
            hidden = np.maximum(hidden_pre, 0)
            logits = hidden @ weights_2.T + bias_2
            logits -= logits.max(axis=1, keepdims=True)
            probabilities = np.exp(logits)
            probabilities /= probabilities.sum(axis=1, keepdims=True)
            probabilities[np.arange(len(indices)), batch_y] -= 1.0

            gradient_w_2 = probabilities.T @ hidden / len(indices)
            gradient_b_2 = probabilities.mean(axis=0)
            gradient_hidden = probabilities @ weights_2
            gradient_hidden[hidden_pre <= 0] = 0
            gradient_w_1 = gradient_hidden.T @ batch_x / len(indices)
            gradient_b_1 = gradient_hidden.mean(axis=0)
            gradients = [gradient_w_1, gradient_b_1, gradient_w_2, gradient_b_2]

            for parameter, gradient, first, second in zip(
                parameters, gradients, first_moments, second_moments
            ):
                gradient += 0.00005 * parameter
                first *= 0.9
                first += 0.1 * gradient
                second *= 0.999
                second += 0.001 * gradient * gradient
                first_hat = first / (1 - 0.9**step)
                second_hat = second / (1 - 0.999**step)
                parameter -= learning_rate * first_hat / (np.sqrt(second_hat) + 1e-8)

        print(f"epoch {epoch + 1:02d}/{epochs}: learning_rate={learning_rate:.4f}")

    return weights_1, bias_1, weights_2, bias_2


def css_number(value: float) -> str:
    text = f"{float(value):.7f}".rstrip("0").rstrip(".")
    return "0" if text in {"-0", ""} else text


def write_model_css(
    images: np.ndarray,
    weights_1: np.ndarray,
    bias_1: np.ndarray,
    weights_2: np.ndarray,
    bias_2: np.ndarray,
    scores: np.ndarray,
) -> None:
    floor = float(scores.min()) - 0.5
    ceiling = float(scores.max()) + 0.5
    scale = 100.0 / (ceiling - floor)

    lines = [
        "/* Generated by tools/build.py. The browser evaluates these expressions. */",
        ":root {",
        f"  --score-floor: {css_number(floor)};",
        f"  --bar-scale: {css_number(scale)};",
    ]
    for index in range(784):
        lines.append(f"  --x-{index:03d}: 0;")
    for hidden_index in range(len(bias_1)):
        lines.append(
            f"  --hidden-bias-{hidden_index:02d}: {css_number(bias_1[hidden_index])};"
        )
        for pixel_index, value in enumerate(weights_1[hidden_index]):
            lines.append(
                f"  --hidden-w-{hidden_index:02d}-{pixel_index:03d}: {css_number(value)};"
            )
        terms = [f"var(--hidden-bias-{hidden_index:02d})"]
        terms.extend(
            f"var(--x-{pixel_index:03d}) * var(--hidden-w-{hidden_index:02d}-{pixel_index:03d})"
            for pixel_index in range(784)
        )
        lines.append(f"  --hidden-pre-{hidden_index:02d}: calc(")
        lines.append("    " + "\n    + ".join(terms))
        lines.append("  );")
        lines.append(
            f"  --hidden-{hidden_index:02d}: max(0, var(--hidden-pre-{hidden_index:02d}));"
        )

    for class_index in range(10):
        lines.append(f"  --output-bias-{class_index}: {css_number(bias_2[class_index])};")
        for hidden_index, value in enumerate(weights_2[class_index]):
            lines.append(
                f"  --output-w-{class_index}-{hidden_index:02d}: {css_number(value)};"
            )
        terms = [f"var(--output-bias-{class_index})"]
        terms.extend(
            f"var(--hidden-{hidden_index:02d}) * var(--output-w-{class_index}-{hidden_index:02d})"
            for hidden_index in range(len(bias_1))
        )
        lines.append(f"  --score-{class_index}: calc(")
        lines.append("    " + "\n    + ".join(terms))
        lines.append("  );")
    lines.append("}")

    for sample_index, image in enumerate(images):
        lines.append(f":root:has(#sample-{sample_index}:checked) {{")
        for pixel_index, value in enumerate(image):
            if value != 0:
                lines.append(f"  --x-{pixel_index:03d}: {css_number(value)};")
        lines.append("}")
        lines.append(
            f':root:has(#sample-{sample_index}:checked) '
            f'.active-image[data-sample="{sample_index}"] {{ display: block; }}'
        )
        lines.append(
            f':root:has(#sample-{sample_index}:checked) '
            f'.sample-detail[data-sample="{sample_index}"],'
        )
        lines.append(
            f':root:has(#sample-{sample_index}:checked) '
            f'.reference-detail[data-sample="{sample_index}"] {{ display: flex; }}'
        )
    (ROOT / "model.css").write_text("\n".join(lines) + "\n")


def write_sample_svgs(images: np.ndarray) -> None:
    sample_dir = ROOT / "samples"
    sample_dir.mkdir(exist_ok=True)
    for sample_index, image in enumerate(images):
        rects = []
        for pixel_index, value in enumerate(image):
            if value == 0:
                continue
            x = pixel_index % 28
            y = pixel_index // 28
            lightness = float(value) * 82
            rects.append(
                f'<rect x="{x}" y="{y}" width="1" height="1" '
                f'fill="hsl(238 70% {lightness:.2f}%)"/>'
            )
        svg = (
            '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 28 28" '
            'shape-rendering="crispEdges">'
            '<rect width="28" height="28" fill="#050506"/>'
            + "".join(rects)
            + "</svg>\n"
        )
        (sample_dir / f"sample-{sample_index}.svg").write_text(svg)


def write_html(
    sample_indices: np.ndarray,
    expected: np.ndarray,
    reference_predictions: np.ndarray,
    accuracy: float,
) -> None:
    active_images = "\n".join(
        f'''          <img class="active-image" data-sample="{sample_index}"
            src="samples/sample-{sample_index}.svg"
            alt="MNIST test image of the digit {int(label)}">'''
        for sample_index, label in enumerate(expected)
    )
    sample_details = "\n".join(
        f'''          <span class="sample-detail" data-sample="{sample_index}">
            <span>MNIST test sample {int(dataset_index)}</span>
            <strong>Label: {int(label)}</strong>
          </span>'''
        for sample_index, (dataset_index, label) in enumerate(
            zip(sample_indices, expected)
        )
    )
    sample_options = "\n".join(
        f'''          <input type="radio" name="sample" id="sample-{sample_index}"{(" checked" if sample_index == 0 else "")}>
          <label for="sample-{sample_index}" title="Try digit {int(label)}">
            <img src="samples/sample-{sample_index}.svg" alt="">
            <span>{int(label)}</span>
          </label>'''
        for sample_index, label in enumerate(expected)
    )
    reference_details = "\n".join(
        f'''          <span class="reference-detail" data-sample="{sample_index}">
            <span>Python reference prediction</span>
            <strong>{int(prediction)}</strong>
          </span>'''
        for sample_index, prediction in enumerate(reference_predictions)
    )
    rows = "\n".join(
        f'''          <div class="score-row" data-class="{class_index}">
            <span class="class-label">{class_index}</span>
            <div class="bar"><div class="bar-fill"></div></div>
            <span class="score-value" aria-label="CSS score in thousandths"></span>
          </div>'''
        for class_index in range(10)
    )
    document = f'''<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>MNIST, computed by CSS</title>
  <link rel="stylesheet" href="model.css">
  <link rel="stylesheet" href="styles.css">
</head>
<body>
  <main>
    <p class="eyebrow">Experiment 001 · no runtime JavaScript</p>
    <h1>MNIST, computed by CSS.</h1>
    <p class="lede">
      A real 784-input linear classifier. The image and trained weights are CSS
      variables; choose a test image and the ten bars will be recomputed by ten
      browser-evaluated <code>calc()</code> dot products.
    </p>

    <section class="experiment" aria-label="MNIST classifier result">
      <div class="card">
        <div class="digit-grid">
{active_images}
        </div>
        <div class="caption">
{sample_details}
        </div>
        <fieldset class="sample-picker">
          <legend>Try another test image</legend>
          <div class="sample-options">
{sample_options}
          </div>
        </fieldset>
      </div>

      <div class="results">
        <h2>Class scores</h2>
        <p class="hint">The longest bar is the CSS prediction.</p>
        <div class="scores">
{rows}
        </div>
        <div class="status">
{reference_details}
        </div>
        <p class="proof">
          Reference test accuracy: <strong>{accuracy * 100:.2f}%</strong>.
          Inspect <code>model.css</code> to see the 784→32→10 network and its
          ReLU activations. This document contains no
          <code>&lt;script&gt;</code> element.
        </p>
      </div>
    </section>
  </main>
</body>
</html>
'''
    (ROOT / "index.html").write_text(document)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--epochs", type=int, default=8)
    parser.add_argument("--seed", type=int, default=7)
    args = parser.parse_args()

    x_train, y_train, x_test, y_test = load_data()
    weights_1, bias_1, weights_2, bias_2 = train(
        x_train, y_train, args.epochs, args.seed
    )
    test_hidden = np.maximum(x_test @ weights_1.T + bias_1, 0)
    test_scores = test_hidden @ weights_2.T + bias_2
    predictions = test_scores.argmax(axis=1)
    accuracy = float((predictions == y_test).mean())

    sample_indices = np.array(
        [
            np.flatnonzero((y_test == digit) & (predictions == digit))[0]
            for digit in range(10)
        ]
    )
    images = x_test[sample_indices]
    scores = test_scores[sample_indices]
    expected = y_test[sample_indices]
    reference_predictions = predictions[sample_indices]
    print(f"test accuracy: {accuracy * 100:.2f}%")
    print("samples:")
    for sample_index, dataset_index in enumerate(sample_indices):
        print(
            f"  {sample_index}: test[{dataset_index}] "
            f"expected={expected[sample_index]}, "
            f"predicted={reference_predictions[sample_index]}"
        )

    write_model_css(images, weights_1, bias_1, weights_2, bias_2, scores)
    write_sample_svgs(images)
    write_html(sample_indices, expected, reference_predictions, accuracy)
    print("wrote index.html, model.css, and 10 sample SVGs")


if __name__ == "__main__":
    main()
