#!/usr/bin/env node
// debug_b.mjs -- load pages/b-chain-L0.html with html.go-1, read intermediate values + box widths.
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const dependencyRoot = "/Users/shubhampatil/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules";
const executablePath = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome";
const here = path.dirname(new URL(import.meta.url).pathname);
const page = process.argv[2] ?? "pages/b-chain-L0.html";
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const { chromium } = require(`${dependencyRoot}/playwright`);
const browser = await chromium.launch({ executablePath, headless: true, args: ["--allow-file-access-from-files"] });
const context = await browser.newContext({ javaScriptEnabled: false });
const pw = await context.newPage();
const cdp = await context.newCDPSession(pw);
await cdp.send("DOM.enable"); await cdp.send("CSS.enable");
await pw.goto(`file://${path.resolve(here, page)}`, { waitUntil: "load" });
await sleep(1500);
const { root } = await cdp.send("DOM.getDocument", { depth: 1 });
const htmlId = root.children.find((c) => c.localName === "html").nodeId;
await cdp.send("DOM.setAttributeValue", { nodeId: htmlId, name: "class", value: "go-1" });
await sleep(2500);
const q = async (sel) => (await cdp.send("DOM.querySelector", { nodeId: root.nodeId, selector: sel })).nodeId;
const props = async (sel, names) => { const id = await q(sel); if (!id) return `${sel}: not found`; const { computedStyle } = await cdp.send("CSS.getComputedStyleForNode", { nodeId: id }); const m = new Map(computedStyle.map((p) => [p.name, p.value])); return Object.fromEntries(names.map((n) => [n, m.get(n)])); };
const box = async (sel) => { const id = await q(sel); if (!id) return `${sel}: not found`; try { const { model } = await cdp.send("DOM.getBoxModel", { nodeId: id }); return { w: model.width, h: model.height }; } catch (e) { return `${sel}: ${e.message}`; } };
const out = {};
out.in = await props("#in", ["--range-fc", "--n2-000", "--n2-001"]);
out.fcStage = await props(".fc", ["font-family", "font-size", "font-style"]);
out.fcSettingsLen = ((await props(".fc", ["font-variation-settings"]))["font-variation-settings"] ?? "").length;
for (const i of [0, 1, 2, 3]) out[`fcRow${i}`] = await box(`.fc [style*="--f${i}\"]`);
out.fc0c0 = await box("#fc0c0");
out.fc0r0 = await props("#fc0r0", ["--hidden-000", "--hidden-001"]);
out.fc0r1 = await props("#fc0r1", ["--hidden-002", "--hidden-003"]);
out.hm0 = await box("#hm0");
out.pm0 = await box("#pm0");
out.pr0 = await props("#pr0", ["--range-proj", "--hidden-000", "--hidden-255"]);
out.ps0 = await props("#ps0", ["font-family", "font-size"]);
out.ps0SettingsLen = ((await props("#ps0", ["font-variation-settings"]))["font-variation-settings"] ?? "").length;
out.ps0SettingsHead = ((await props("#ps0", ["font-variation-settings"]))["font-variation-settings"] ?? "").slice(0, 120);
for (const j of [0, 1, 11]) out[`projRow${j}_0`] = await box(`#ps${j} [style*="--p${j}_0\"]`);
out.om0 = await box("#om0"); out.or0 = await props("#or0", ["--range-proj"]);
out.o0c0 = await box("#o0c0");
out.o0r0 = await props("#o0r0", ["--out-000", "--out-001"]);
out.out0 = await props("#out0", ["--out-000", "--out-001", "--out-002", "--out-003"]);
console.log(JSON.stringify(out, null, 1));
await browser.close();
