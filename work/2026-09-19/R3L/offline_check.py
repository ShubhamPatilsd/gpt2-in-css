"""R3L offline check: <R3L bundle> vs <reference bundle built with the R3L flags off> (= combined3's recipe).

Modes (auto-detected from the bundle manifest): font (R3L_FONT_LOOP) or packed (R3L_PACKED_LOOP).
1. Strip from both runtime.css files exactly the loop-bank latch rules (base transition lists, write rules, the
   `.loop-scroll,.loop-track` forwards, the latch `@property` registrations, their `initial` entries in the reset
   lists, and in font mode the 6 `@font-face` + `.lf-*` / `.lh` / `.ll` / `.loop-metric{…}` / track
   `font-variation-settings` rules) and from both index.html files the carrier markup; the remainders must be
   byte-identical (nothing else changed).
2. The R3L bundle's write declarations, transition lists, forwards and carriers must equal r3l_packed_loop's spec
   strings; the reference's must be the 769-name form. Counts: 2 (font) / 385 (packed) vs 769 names per bank,
   1,538 carriers in both.
usage: PYTHONPATH=tools python offline_check.py <r3l-bundle-dir> <ref-bundle-dir>
"""
import json, re, sys
from pathlib import Path

import r3l_packed_loop as r3l

W = 768
bundle, ref = Path(sys.argv[1]), Path(sys.argv[2])
manifest = json.loads((bundle / "manifest.json").read_text())
mode = "font" if manifest.get("r3lFontLoop") else "packed" if manifest.get("r3lPackedLoop") else None
if mode is None or (mode == "font") != r3l.FONT_LOOP:
    sys.exit(f"bundle mode {mode!r} does not match the module flags (FONT_LOOP={r3l.FONT_LOOP}); set R3L_FONT_LOOP accordingly")
ok = True


def fail(msg):
    global ok
    ok = False
    print("FAIL:", msg)


LATCH_PROP = r"--(?:saved-[01]-\d+|sv-[01]-\d+|lst-[01]|lh-[01]-\d+|ll-[01]-\d+)"


def strip_css(css):
    n = {}
    css, n["write"] = re.subn(r"@container loopcontrol style\(--loop-phase:[01]\)\{\.loop-bank-[01]\{transition-property:none;[^{}]*\}\}", "", css)
    css, n["base"] = re.subn(r"\.loop-bank-[01]\{transition-property:[^{}]*\}", "", css)
    css, n["reset"] = re.subn(LATCH_PROP + r":initial;", "", css)
    css, n["fwd"] = re.subn(r"\.loop-scroll,\.loop-track\{[^{}]*\}", "", css)
    css, n["props"] = re.subn(r"@property " + LATCH_PROP + r"\{[^{}]*\}", "", css)
    css, n["fontface"] = re.subn(r'@font-face\{font-family:LoopCarrier\d;[^{}]*\}', "", css)
    css, n["glyphcss"] = re.subn(r"\.lf-\d\{font-family:LoopCarrier\d\}|\.loop-metric\{white-space:pre;[^{}]*\}|\.lh\{font-size:\d+px\}|\.ll\{font-size:\d+px\}|\.loop-bank-[01]>\.loop-scroll>\.loop-track\{font-variation-settings:var\(--lst-[01]\)\}", "", css)
    return css, n


def strip_html(html):
    return re.subn(r'<i class="loop-metric[^"]*" style="[^"]*;view-timeline:(--loop-t-\d-\d+) inline">(?:<b class="lh">(?:&#x[0-9A-F]+;)+</b><b class="ll">&#x[0-9A-F]+;</b>)?</i>', r'<carrier \1>', html)


pc, pn = strip_css((bundle / "runtime.css").read_text())
rc, rn = strip_css((ref / "runtime.css").read_text())
print("stripped counts bundle", pn, "ref", rn)
if pn["base"] != 2 or pn["write"] != 2 or pn["fwd"] != 1 or rn["base"] != 2 or rn["write"] != 2 or rn["fwd"] != 1:
    fail("unexpected loop-bank rule counts")
exp_props = 2 * (2 + 2 * W) if mode == "font" else 2 * (W // 2 + 1)
if pn["props"] != exp_props or rn["props"] != 2 * (W + 1):
    fail(f"@property counts {pn['props']} (expected {exp_props}) / {rn['props']}")
if mode == "font" and (pn["fontface"] != 6 or pn["glyphcss"] != 6 + 1 + 2 + 2):
    fail(f"font-mode rule counts fontface {pn['fontface']} glyphcss {pn['glyphcss']}")
# font-witness probes for the 6 extra faces are generated by the runtime (font_barrier); neutralise their indices
if mode == "font":
    pc = re.sub(r"\.font-proof-\d+\{[^{}]*\}", "", pc); rc = re.sub(r"\.font-proof-\d+\{[^{}]*\}", "", rc)
    pc = re.sub(r"--font-proof-\d+", "--font-proof-N", pc); rc = re.sub(r"--font-proof-\d+", "--font-proof-N", rc)
    pc = re.sub(r"\.font-status\{[^{}]*\}|\.font-all-[\w-]*\{[^{}]*\}|\.geometry-[\w-]*\{[^{}]*\}", "", pc); rc = re.sub(r"\.font-status\{[^{}]*\}|\.font-all-[\w-]*\{[^{}]*\}|\.geometry-[\w-]*\{[^{}]*\}", "", rc)
if pc != rc:
    i = next((k for k in range(min(len(pc), len(rc))) if pc[k] != rc[k]), min(len(pc), len(rc)))
    fail(f"runtime.css differs outside the latch rules at offset {i}: bundle …{pc[max(0, i - 100):i + 100]!r} ref …{rc[max(0, i - 100):i + 100]!r}")
else:
    print("runtime.css identical outside the loop-bank latch rules (+ font-witness bookkeeping in font mode)")
ph, pcount = strip_html((bundle / "index.html").read_text())
rh, rcount = strip_html((ref / "index.html").read_text())
if pcount != 2 * (W + 1) or rcount != 2 * (W + 1):
    fail(f"carrier counts {pcount} / {rcount}")
if mode == "font":
    # the font barrier adds one witness + one proof element per face
    ph = re.sub(r'<i class="font-witness"[^>]*>&#x[0-9A-F]+;</i>|<i class="font-proof font-proof-\d+"></i>', "", ph)
    rh = re.sub(r'<i class="font-witness"[^>]*>&#x[0-9A-F]+;</i>|<i class="font-proof font-proof-\d+"></i>', "", rh)
    ph = re.sub(r'<i class="geometry-[^"]*"[^>]*></i>|<i class="head-reduction font-all-[\d-]+"></i>', "", ph); rh = re.sub(r'<i class="geometry-[^"]*"[^>]*></i>|<i class="head-reduction font-all-[\d-]+"></i>', "", rh)
if ph != rh:
    i = next((k for k in range(min(len(ph), len(rh))) if ph[k] != rh[k]), min(len(ph), len(rh)))
    fail(f"index.html differs outside the carriers at offset {i}: bundle …{ph[max(0, i - 100):i + 100]!r} ref …{rh[max(0, i - 100):i + 100]!r}")
else:
    print(f"index.html identical outside the {pcount} carriers (+ font-witness probes in font mode)")

# 2. exact spec strings
css = (bundle / "runtime.css").read_text()
for b in range(2):
    names = r3l.latched_names(b, W)
    base = re.search(rf"\.loop-bank-{b}\{{transition-property:([^;{{}}]*);transition-duration:1ms;transition-delay:86400s;transition-timing-function:steps\(1,end\)([^{{}}]*)\}}", css)
    if not base or base[1].split(",") != names or base[2] != r3l.transition_extra():
        fail(f"bank {b} base transition rule != spec")
    write = re.search(rf"@container loopcontrol style\(--loop-phase:{b}\)\{{\.loop-bank-{b}\{{transition-property:none;([^{{}}]*)\}}\}}", css)
    exp = ";".join(r3l.write_declarations(b, W, "var(--native-pass)"))
    if not write or write[1] != exp:
        fail(f"bank {b} write declarations != spec")
    else:
        print(f"bank {b}: {len(names)} latched names ({names}), write rule = spec ({len(write[1]):,} B)")
fwd = re.search(r"\.loop-scroll,\.loop-track\{([^{}]*)\}", css)
exp = ";".join(f"{n}:inherit" for b in range(2) for n in r3l.latched_names(b, W))
if not fwd or fwd[1] != exp:
    fail("scroll/track forwards != spec")
html = (bundle / "index.html").read_text()
carriers = re.findall(r'(<i class="loop-metric[^"]*" style="[^"]*;view-timeline:--loop-t-(\d)-(\d+) inline">(?:<b class="lh">(?:&#x[0-9A-F]+;)+</b><b class="ll">&#x[0-9A-F]+;</b>)?</i>)', html)
if len(carriers) != 2 * (W + 1):
    fail(f"{len(carriers)} carriers")
bad = [(b, i) for markup, b, i in carriers if markup != r3l.carrier_markup(int(b), int(i), W, f"--loop-t-{b}-{i}")]
if bad:
    fail(f"{len(bad)} carriers != spec, first {bad[:3]}")
else:
    print(f"{len(carriers)} carriers = spec (e.g. {carriers[0][0][:150]}…)")
if mode == "font":
    faces = re.findall(r'@font-face\{font-family:LoopCarrier(\d);src:url\("([^"]+)"\) format\("(?:woff2|truetype)"\)\}', css)
    print("loop-carrier faces:", [(k, u) for k, u in faces][:2], "…", len(faces))
    if any("F4" in u or "experiments" in u for _, u in faces):
        fail("loop-carrier font URL points outside R3L")
    priv = re.findall(r"@property --l[hl]-[01]-\d+\{syntax:\"<number>\";inherits:(\w+);initial-value:0\}", css)
    lst = re.findall(r"@property --lst-[01]\{syntax:\"\*\";inherits:(\w+);initial-value:\"H000\" 0\}", css)
    if len(priv) != 4 * W or set(priv) != {"false"} or len(lst) != 2 or set(lst) != {"false"}:
        fail(f"registrations: {len(priv)} lh/ll ({set(priv)}), {len(lst)} lst ({set(lst)})")
    else:
        print(f"{len(priv)} --lh/--ll and 2 --lst registrations, all inherits:false")
rcss = (ref / "runtime.css").read_text()
rbase = re.search(r"\.loop-bank-0\{transition-property:([^;{}]*);", rcss)
print("reference bank 0 list length:", len(rbase[1].split(",")) if rbase else None)
print("RESULT:", "ok" if ok else "FAILED")
sys.exit(0 if ok else 1)
